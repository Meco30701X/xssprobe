// DetectWAF sends a probe request and fingerprints the WAF
func DetectWAF(targetURL string, cookies []string, headers map[string]string) *WAFResult {
	// Build probe URL with malicious-looking parameter
	probeURL := buildProbeURL(targetURL)

	client := &http.Client{
		Timeout: 10 * time.Second,
		// Don't follow redirects to see WAF response
		CheckRedirect: func(req *http.Request, via []*http.Request) error {
			return http.ErrUseLastResponse
		},
	}

	req, err := http.NewRequest("GET", probeURL, nil)
	if err != nil {
		return &WAFResult{Detected: false, Detail: "request error: " + err.Error()}
	}

	// Add cookies
	for _, cookie := range cookies {
		parts := strings.SplitN(cookie, "=", 2)
		if len(parts) == 2 {
			req.AddCookie(&http.Cookie{Name: parts[0], Value: parts[1]})
		}
	}

	// Add custom headers
	for k, v := range headers {
		req.Header.Set(k, v)
	}

	// Set a realistic User-Agent
	req.Header.Set("User-Agent", "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36")

	resp, err := client.Do(req)
	if err != nil {
		return &WAFResult{Detected: false, Detail: "request error: " + err.Error()}
	}
	defer resp.Body.Close()

	// Read response body (limit to 100KB)
	bodyBytes, _ := io.ReadAll(io.LimitReader(resp.Body, 100*1024))
	body := strings.ToLower(string(bodyBytes))

	// Collect response headers
	respHeaders := make(map[string][]string)
	for key, values := range resp.Header {
		respHeaders[strings.ToLower(key)] = values
	}

	// Check against known WAF signatures
	for _, sig := range getWAFSignatures() {
		score := 0
		details := []string{}

		// Check headers
		for headerName, headerValues := range sig.Headers {
			if respValues, ok := respHeaders[headerName]; ok {
				if len(headerValues) == 0 {
					// Just checking presence
					score += 2
					details = append(details, fmt.Sprintf("header %s present", headerName))
				} else {
					for _, pattern := range headerValues {
						for _, respVal := range respValues {
							if strings.Contains(strings.ToLower(respVal), pattern) {
								score += 3
								details = append(details, fmt.Sprintf("header %s=%s", headerName, respVal))
								break
							}
						}
					}
				}
			}
		}

		// Check body patterns
		for _, pattern := range sig.BodyMatch {
			if strings.Contains(body, pattern) {
				score += 2
				details = append(details, fmt.Sprintf("body contains '%s'", pattern))
			}
		}

		// Check status code
		for _, code := range sig.StatusCodes {
			if resp.StatusCode == code {
				score += 1
				details = append(details, fmt.Sprintf("status %d", code))
			}
		}

		// Determine if WAF detected
		if score >= 3 {
			confidence := "low"
			if score >= 5 {
				confidence = "medium"
			}
			if score >= 7 {
				confidence = "high"
			}

			return &WAFResult{
				Detected:   true,
				Name:       sig.Name,
				Detail:     strings.Join(details, ", "),
				Confidence: confidence,
			}
		}
	}

	// Check for generic blocking patterns
	if resp.StatusCode == 403 || resp.StatusCode == 406 {
		blockPatterns := []string{
			"blocked", "forbidden", "access denied",
			"not acceptable", "request rejected",
			"security", "firewall", "protection",
		}
		for _, pattern := range blockPatterns {
			if strings.Contains(body, pattern) {
				return &WAFResult{
					Detected:   true,
					Name:       "generic",
					Detail:     fmt.Sprintf("status %d, body contains '%s'", resp.StatusCode, pattern),
					Confidence: "low",
				}
			}
		}
	}

	return &WAFResult{
		Detected: false,
		Detail:   fmt.Sprintf("no WAF detected (status: %d)", resp.StatusCode),
	}
}

// buildProbeURL creates a URL with a malicious-looking parameter
func buildProbeURL(baseURL string) string {
	probe := `<script>alert(1)</script>`

	if strings.Contains(baseURL, "?") {
		return baseURL + "&q=" + probe
	}
	return baseURL + "?q=" + probe
}

// PrintWAFResult prints WAF detection result
func PrintWAFResult(result *WAFResult) {
	if result.Detected {
		fmt.Printf("[!] WAF Detected: %s (confidence: %s)\n", result.Name, result.Confidence)
		fmt.Printf("    Detail: %s\n", result.Detail)
	} else {
		fmt.Printf("[*] No WAF detected\n")
	}
}

// GetRecommendedWAF returns the WAF name for payload selection
// Maps similar WAFs to our supported types
func GetRecommendedWAF(detected string) string {
	switch strings.ToLower(detected) {
	case "cloudflare":
		return "cloudflare"
	case "aws", "awswaf":
		return "aws"
	case "modsec", "modsecurity":
		return "modsec"
	case "akamai", "imperva", "incapsula", "sucuri", "f5", "bigip":
		return "generic" // Use generic bypass for these
	default:
		return ""
	}
}
