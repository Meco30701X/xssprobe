// WAFResult holds WAF detection result
type WAFResult struct {
	Detected bool
	Name     string // cloudflare, aws, modsec, generic
	Detail   string // How it was detected
	Confidence string // high, medium, low
}

// WAFSignature defines how to identify a WAF
